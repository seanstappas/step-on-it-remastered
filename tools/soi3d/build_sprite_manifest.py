#!/usr/bin/env python3
"""build_sprite_manifest.py -- assemble extracted/sprites_3d/manifest.json from per-family meta.json fragments.

WHY: parallel agents each own ONE family folder. Instead of all of them editing one shared manifest.json
(write contention / merge conflicts), each writes ONLY its own extracted/sprites_3d/<family>/meta.json.
This tool DISCOVERS every <family>/meta.json and merges them into the aggregate manifest.json the runtime
reads. The aggregate is GENERATED -- never hand-edit it; edit the per-family meta.json and re-run this.

Fragment schema (extracted/sprites_3d/<family>/meta.json). Asset paths are BARE names relative to that
family folder; the builder prefixes them with "<family>/". The family name = the folder name.
  {
    "class": "A",                         # A spin | B static/simple | (C/D stay 2D, no folder here)
    "motion": "spin",                     # free text: spin | flip | static | ...
    "source": "extracted/sprites/<fam>",  # the original 2D sheet folder (repo-relative, left as-is)
    "stills": ["disk.png"],               # published reference still(s) in this folder
    "model": "disk.glb",                  # the model the engine spins live (or null / omit if none)
    "model_status": "pending-P1",         # optional
    "spin_dps": 90, "spin_dir": "cw",     # motion params (spinners); read by the runtime
    "tilt_deg": 0, "px": 128,
    "...": "any extra keys pass through unchanged (static, todo, extra_assets, ...)"
  }

Usage:
  py tools/soi3d/build_sprite_manifest.py [--root extracted/sprites_3d]
  py tools/soi3d/build_sprite_manifest.py --check      # CI: exit 1 if manifest.json is stale, don't write
"""
import argparse
import glob
import json
import os
import sys

PATH_LIST_KEYS = ("stills", "extra_assets")   # lists of family-relative filenames -> prefixed with <family>/
PATH_STR_KEYS = ("model",)                     # single family-relative filename (or null) -> prefixed


def build(root):
    families = {}
    for meta_path in sorted(glob.glob(os.path.join(root, "*", "meta.json"))):
        fam = os.path.basename(os.path.dirname(meta_path))
        with open(meta_path, "r", encoding="utf-8") as f:
            m = json.load(f)
        m.pop("family", None)   # the folder name is authoritative
        entry = {}
        for k, v in m.items():
            if k in PATH_LIST_KEYS and isinstance(v, list):
                entry[k] = ["%s/%s" % (fam, x) for x in v]
            elif k in PATH_STR_KEYS and isinstance(v, str):
                entry[k] = "%s/%s" % (fam, v)
            else:
                entry[k] = v
        entry.setdefault("verify", "%s/_verify" % fam)
        families[fam] = entry
    return {
        "_note": (
            "GENERATED by tools/soi3d/build_sprite_manifest.py from each extracted/sprites_3d/<family>/meta.json. "
            "DO NOT hand-edit this file -- edit the per-family meta.json and re-run (this is what lets parallel "
            "agents publish without touching a shared file). RUNTIME (P1, --3d): for each Class A/B family the "
            "engine loads <model> and spins it LIVE in a Godot SubViewport with an ORTHOGRAPHIC camera (2D "
            "output) -- it does NOT bake sprite frames. Stills + everything under _verify/ are validation only. "
            "Layout + rationale: plan/SPRITE_REMASTER_PROCESS.md sec.5."
        ),
        "root": root.replace(os.sep, "/"),
        "families": {k: families[k] for k in sorted(families)},
    }


def main():
    ap = argparse.ArgumentParser(description="Build sprites_3d/manifest.json from per-family meta.json fragments.")
    ap.add_argument("--root", default="extracted/sprites_3d", help="root folder of the 3D sprite families")
    ap.add_argument("--check", action="store_true", help="exit 1 if manifest.json is out of date (do not write)")
    a = ap.parse_args()
    out_path = os.path.join(a.root, "manifest.json")
    data = build(a.root)
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if a.check:
        cur = open(out_path, "r", encoding="utf-8").read() if os.path.exists(out_path) else ""
        if cur != text:
            print("OUT OF DATE:", out_path, "-- run: py tools/soi3d/build_sprite_manifest.py")
            sys.exit(1)
        print("up to date:", out_path)
        return
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    fams = ", ".join(data["families"]) or "(none)"
    print("wrote", out_path, "from", len(data["families"]), "fragment(s):", fams)


if __name__ == "__main__":
    main()
